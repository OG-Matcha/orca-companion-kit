#!/bin/sh
# Install Orca Companion Kit on macOS: ~/Applications/Orca Companion.app starts Orca through the launcher.
# The app holds one shell script pointing at this repo, so a `git pull` needs no reinstall (moving the repo
# does). Nothing inside Orca.app is touched. Undo with uninstall.sh.
set -eu

REPO=$(cd "$(dirname "$0")" && pwd)
APP="$HOME/Applications/Orca Companion.app"

if [ -n "${ORCA_APP:-}" ]; then
  ORCA="$ORCA_APP"
elif [ -d /Applications/Orca.app ]; then
  ORCA=/Applications/Orca.app
else
  ORCA="$HOME/Applications/Orca.app"
fi
[ -x "$ORCA/Contents/MacOS/Orca" ] || { echo "Orca not found at $ORCA. Install Orca first, or set ORCA_APP." >&2; exit 1; }

# Finder starts apps with a bare PATH (no Homebrew, no nvm), so the app calls node by its full path.
NODE=$(command -v node) || { echo 'node not found: install Node.js 20 or later first.' >&2; exit 1; }
"$NODE" -e 'process.exit(Number(process.versions.node.split(".")[0]) < 20 ? 1 : 0)' || { echo "Node.js 20 or later is needed ($NODE is $("$NODE" -v))." >&2; exit 1; }

# These paths are written into a shell script below; keep them free of characters it would expand.
for p in "$REPO" "$NODE" "$ORCA"; do
  case "$p" in
    *'"'* | *'$'* | *'`'* | *'\'*) echo "path has a character the launcher script cannot hold, move it: $p" >&2; exit 1 ;;
  esac
done

if [ ! -d "$REPO/node_modules" ]; then
  echo 'installing npm dependencies...'
  (cd "$REPO" && npm install --omit=dev --no-audit --no-fund)
fi

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# LSUIElement: the launcher runs in the background without a Dock icon of its own; Orca shows its usual one.
cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Orca Companion</string>
  <key>CFBundleIdentifier</key><string>io.github.orca-companion-kit.launcher</string>
  <key>CFBundleExecutable</key><string>orca-companion</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/orca-companion" <<SCRIPT
#!/bin/sh
# Starts Orca through Orca Companion Kit. Generated by install.sh.
export ORCA_APP="$ORCA"
cd "$REPO"
exec "$NODE" "$REPO/src/themer.mjs"
SCRIPT
chmod +x "$APP/Contents/MacOS/orca-companion"

[ -f "$ORCA/Contents/Resources/icon.icns" ] && cp "$ORCA/Contents/Resources/icon.icns" "$APP/Contents/Resources/icon.icns"

echo "done: $APP"
echo 'Open Orca from it (drag it to the Dock, in place of Orca); Control+Option+T opens the theme picker.'
echo 'Optional: npm run example  (copies the example theme + the Puff companion into ~/.orca/themer)'
