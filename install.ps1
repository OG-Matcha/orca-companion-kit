# Install Orca Companion Kit: a renamed node host, a hidden launcher, and Orca shortcuts pointing at it.
# The launcher re-points the shortcuts itself after Orca updates (src/shortcuts.ps1). Undo with uninstall.ps1.
# Nothing inside Orca's install folder is touched.
$ErrorActionPreference = 'Stop'
$repo = $PSScriptRoot
$bin = Join-Path $repo 'bin'
$hostExe = Join-Path $bin 'orca-companion.exe'
$vbs = Join-Path $repo 'Orca Companion.vbs'
$backup = Join-Path $repo 'backup'
$orcaExe = Join-Path $env:LOCALAPPDATA 'Programs\orca\Orca.exe'

if (-not (Test-Path $orcaExe)) { throw "Orca not found at $orcaExe. Install Orca first (per-user install)." }
if (-not (Test-Path (Join-Path $repo 'node_modules'))) {
  Write-Host 'installing npm dependencies...'
  Push-Location $repo
  try { npm install --omit=dev --no-audit --no-fund | Out-Host } finally { Pop-Location }
}
New-Item -ItemType Directory -Force $bin, $backup | Out-Null

# Why a renamed copy of node: `taskkill /IM node.exe` (a common cleanup) must not take Orca down with the
# launcher; Orca closes when the launcher's private pipe closes.
$node = (Get-Command node -ErrorAction Stop).Source
Copy-Item $node $hostExe -Force

# The .vbs starts the launcher without a console window. Generated here because it holds absolute paths.
@"
' Starts Orca through Orca Companion Kit without a console window. Generated by install.ps1.
CreateObject("WScript.Shell").CurrentDirectory = "$repo"
CreateObject("WScript.Shell").Run """$hostExe"" ""$repo\src\themer.mjs""", 0, False
"@ | Set-Content -Path $vbs -Encoding Unicode

Remove-Item (Join-Path $backup 'uninstalled') -ErrorAction SilentlyContinue
& (Join-Path $repo 'src\shortcuts.ps1') -Repo $repo
Write-Host 'done. Open Orca from its shortcut; Ctrl+Alt+T opens the theme picker.'
Write-Host 'Optional: npm run example  (copies the example theme + the Puff companion into ~/.orca/themer)'
